// leanToolchain is the Lean release the rendered Lake project builds with.
const leanToolchain = "leanprover/lean4:v4.35.0"

// lakeManifest is the manifest lake writes for the rendered project, which
// has no dependencies, rendered so a build leaves the tree as it was.
const lakeManifest = `{"version": "1.3.0",
 "packagesDir": ".lake/packages",
 "packages": [],
 "name": "machines",
 "lakeDir": ".lake",
 "fixedToolchain": false}
`

const generatedBy = "Code generated by latere.ai/x/pkg/statemachine/statemachinetest. DO NOT EDIT."

var (
	//go:embed model/Statemachine.lean
	statemachineLean string
	//go:embed model/Transition.tla
	transitionTLA string
)

// Models holds the formal models under dir to the tables: a Lake project
// with a Lean model of each table, and a TLA+ model of each table under
// concurrent writers. With update it writes them and removes the generated
// files no table produces any more; without, it fails t on any difference,
// so a table that changed without its models fails the test that calls it.
//
// A table's claims are written by hand in dir/Proofs/<Name>.lean. The
// rendered lakefile builds that library only while it has a file, so the
// first proof file is followed by one run with update.
//
// Call it from a test with the repository's -update flag:
//
//	var update = flag.Bool("update", false, "rewrite the formal models")
//
//	func TestFormalModels(t *testing.T) {
//		statemachinetest.Models(t, "../../formal", *update, store.Deploys.Graph())
//	}
func Models(t testing.TB, dir string, update bool, graphs ...statemachine.Graph) {
	t.Helper()
	files, err := render(dir, graphs)
	if err != nil {
		t.Fatal(err)
	}
	stale, err := generatedFiles(dir)
	if err != nil {
		t.Fatal(err)
	}
	stale = slices.DeleteFunc(stale, func(p string) bool { _, ok := files[p]; return ok })
	if update {
		for _, p := range slices.Sorted(maps.Keys(files)) {
			full := filepath.Join(dir, p)
			if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(full, files[p], 0o644); err != nil {
				t.Fatal(err)
			}
		}
		for _, p := range stale {
			if err := os.Remove(filepath.Join(dir, p)); err != nil {
				t.Fatal(err)
			}
		}
		return
	}
	var problems []string
	for _, p := range slices.Sorted(maps.Keys(files)) {
		have, err := os.ReadFile(filepath.Join(dir, p))
		switch {
		case errors.Is(err, fs.ErrNotExist):
			problems = append(problems, p+" is missing")
		case err != nil:
			t.Fatal(err)
		case !bytes.Equal(have, files[p]):
			problems = append(problems, p+" differs from its table")
		}
	}
	for _, p := range stale {
		problems = append(problems, p+" is generated but no table produces it")
	}
	if len(problems) > 0 {
		t.Errorf("the formal models under %s do not match the tables; rerun this test with -update "+
			"and commit the result, then fix any proof or model check that fails:\n  %s",
			dir, strings.Join(problems, "\n  "))
	}
}

// generatedFiles lists, relative to dir, the files under it that carry the
// generated header.
func generatedFiles(dir string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if errors.Is(err, fs.ErrNotExist) && p == dir {
			return filepath.SkipDir
		}
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == ".lake" {
				return filepath.SkipDir
			}
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		first, _, _ := strings.Cut(string(b), "\n")
		if strings.HasSuffix(first, generatedBy) {
			rel, err := filepath.Rel(dir, p)
			if err != nil {
				return err
			}
			out = append(out, filepath.ToSlash(rel))
		}
		return nil
	})
	return out, err
}

// render returns every generated file under dir by its slash-separated path
// relative to dir.
func render(dir string, graphs []statemachine.Graph) (map[string][]byte, error) {
	proofs, err := filepath.Glob(filepath.Join(dir, "Proofs", "*.lean"))
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{
		"lean-toolchain":     []byte(leanToolchain + "\n"),
		"lakefile.toml":      []byte(lakefile(len(proofs) > 0)),
		"Statemachine.lean":  []byte("-- " + generatedBy + "\n\n" + statemachineLean),
		"Transition.tla":     []byte(`\* ` + generatedBy + "\n" + transitionTLA),
		".gitignore":         []byte("# " + generatedBy + "\n/.lake/\n"),
		"lake-manifest.json": []byte(lakeManifest),
	}
	for _, g := range graphs {
		if _, dup := files["Machines/"+g.Name+".lean"]; dup {
			return nil, fmt.Errorf("statemachinetest: two tables are named %s", g.Name)
		}
		files["Machines/"+g.Name+".lean"] = []byte(lean(g))
		files[g.Name+".tla"] = []byte(tla(g))
		files[g.Name+".cfg"] = []byte(cfg(g, true))
		if staleBreaks(g) {
			files[g.Name+".stale.cfg"] = []byte(cfg(g, false))
		}
	}
	return files, nil
}

func lakefile(proofs bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n", generatedBy)
	b.WriteString("name = \"machines\"\n")
	if proofs {
		b.WriteString("defaultTargets = [\"Statemachine\", \"Machines\", \"Proofs\"]\n")
	} else {
		b.WriteString("defaultTargets = [\"Statemachine\", \"Machines\"]\n")
	}
	b.WriteString("\n[[lean_lib]]\nname = \"Statemachine\"\n")
	b.WriteString("\n[[lean_lib]]\nname = \"Machines\"\nglobs = [\"Machines.+\"]\n")
	if proofs {
		b.WriteString("\n[[lean_lib]]\nname = \"Proofs\"\nglobs = [\"Proofs.+\"]\n")
	}
	return b.String()
}

var plainIdent = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

// ctor is the Lean constructor of state s, always escaped, so a state named
// like a keyword is still an identifier.
func ctor(s string) string { return ".«" + s + "»" }

func lean(g statemachine.Graph) string {
	var b strings.Builder
	fmt.Fprintf(&b, "-- %s\n\nimport Statemachine\n\n", generatedBy)
	fmt.Fprintf(&b, "/-! The %s table. -/\n\nnamespace Machines.%s\n\n", g.Name, g.Name)
	b.WriteString("inductive State where\n")
	for _, s := range g.States {
		fmt.Fprintf(&b, "  | «%s»\n", s)
	}
	b.WriteString("  deriving DecidableEq, Repr\n\n")
	b.WriteString("def machine : Statemachine.Machine State where\n")
	fmt.Fprintf(&b, "  states := [%s]\n", ctors(g.States))
	fmt.Fprintf(&b, "  initial := [%s]\n", ctors(g.Initial))
	b.WriteString("  next\n")
	for _, s := range g.States {
		fmt.Fprintf(&b, "    | %s => [%s]\n", ctor(s), ctors(g.Next[s]))
	}
	b.WriteString("\n/-- Every state is reached from an initial state. -/\n")
	b.WriteString("theorem all_reachable : machine.AllReachable := by decide\n")
	for _, s := range g.States {
		if len(g.Next[s]) > 0 {
			continue
		}
		name := "terminal_" + s
		if !plainIdent.MatchString(s) {
			name = "«" + name + "»"
		}
		fmt.Fprintf(&b, "\n/-- Nothing follows `%s`. -/\ntheorem %s : machine.Terminal %s := by decide\n", s, name, ctor(s))
	}
	fmt.Fprintf(&b, "\nend Machines.%s\n", g.Name)
	return b.String()
}

func ctors(states []string) string {
	out := make([]string, len(states))
	for i, s := range states {
		out[i] = ctor(s)
	}
	return strings.Join(out, ", ")
}

func tla(g statemachine.Graph) string {
	var b strings.Builder
	fmt.Fprintf(&b, "\\* %s\n", generatedBy)
	fmt.Fprintf(&b, "%s MODULE %s %s\n", strings.Repeat("-", 28), g.Name, strings.Repeat("-", 28))
	fmt.Fprintf(&b, "(* The %s table, for the writers of Transition.tla. *)\nEXTENDS Transition\n\n", g.Name)
	fmt.Fprintf(&b, "MCStates == {%s}\n", quoted(g.States))
	fmt.Fprintf(&b, "MCInitial == {%s}\n", quoted(g.Initial))
	var cases []string
	for _, s := range g.States {
		if len(g.Next[s]) > 0 {
			cases = append(cases, fmt.Sprintf("s = %q -> {%s}", s, quoted(g.Next[s])))
		}
	}
	if len(cases) == 0 {
		b.WriteString("MCSucc == [s \\in MCStates |-> {}]\n")
	} else {
		fmt.Fprintf(&b, "MCSucc == [s \\in MCStates |->\n    CASE %s\n      [] OTHER -> {}]\n", strings.Join(cases, "\n      [] "))
	}
	fmt.Fprintf(&b, "%s\n", strings.Repeat("=", 77))
	return b.String()
}

func quoted(states []string) string {
	out := make([]string, len(states))
	for i, s := range states {
		out[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(out, ", ")
}

// cfg is the TLC configuration of g's model: guarded writers, which must
// keep the table, or writers that check a state read earlier, which TLC
// must catch leaving it.
func cfg(g statemachine.Graph, guarded bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "\\* %s\n", generatedBy)
	writers, flag := "{w1, w2, w3}", "TRUE"
	if guarded {
		fmt.Fprintf(&b, "\\* Writers that check the state they land on keep the %s table.\n", g.Name)
	} else {
		writers, flag = "{w1, w2}", "FALSE"
		b.WriteString("\\* expect violation: Follows\n")
		fmt.Fprintf(&b, "\\* Writers that check a state read earlier leave the %s table.\n", g.Name)
	}
	fmt.Fprintf(&b, "CONSTANTS\n  States <- MCStates\n  Initial <- MCInitial\n  Succ <- MCSucc\n  Writers = %s\n  Guarded = %s\n", writers, flag)
	b.WriteString("SPECIFICATION Spec\nINVARIANT TypeOK\nPROPERTY Follows\n")
	return b.String()
}

// staleBreaks reports whether a writer that checks a state read earlier can
// move a record along a step g does not have: some state a has a successor
// c, and a state b reached from a in one or more steps neither is c nor
// leads to c. Two writers find it: one reads a, the other walks to b, and
// the first writes c over b.
func staleBreaks(g statemachine.Graph) bool {
	for _, a := range g.States {
		for _, b := range reachedFrom(g, a) {
			for _, c := range g.Next[a] {
				if c != b && !slices.Contains(g.Next[b], c) {
					return true
				}
			}
		}
	}
	return false
}

// reachedFrom lists the states reached from a in one or more steps.
func reachedFrom(g statemachine.Graph, a string) []string {
	seen := map[string]bool{}
	queue := slices.Clone(g.Next[a])
	var out []string
	for len(queue) > 0 {
		s := queue[0]
		queue = queue[1:]
		if seen[s] {
			continue
		}
		seen[s] = true
		out = append(out, s)
		queue = append(queue, g.Next[s]...)
	}
	return out
}
